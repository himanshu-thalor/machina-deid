def split_compound_extension(filename: str) -> tuple[str, str]:
    """Split filename into (stem, full_extension), preserving compound CAD/archive suffixes."""
    m = COMPOUND_EXT_RE.search(filename)
    if m:
        idx = m.start(1)
        return filename[:idx], filename[idx:]
    stem, ext = os.path.splitext(filename)
    if ext and (" " in ext or len(ext) > 16):
        return filename, ""
    return stem, ext


def is_safe_engineering_token(token: str) -> bool:
    """Return True if token is an engineering keyword, standard, material, unit, or CAD vendor."""
    t = token.strip().lower()
    if not t:
        return True
    if t in ENGINEERING_STOPWORDS or t in SAFE_CAD_VENDORS or t in SAFE_DOMAINS:
        return True
    # Pure numbers or dimension/metric expressions like 10mm, R3, M4, M8, 2768-c, H7
    if re.fullmatch(r"[\d.,+-]+(?:mm|cm|m|in|deg|rad|kg|g|ml|cc|v|a|w|hz)?", t):
        return True
    if re.fullmatch(r"[mr]?\d+(?:[.,]\d+)?(?:x\d+(?:[.,]\d+)?)?", t):
        return True
    # Common tolerance / GD&T / thread codes
    if re.fullmatch(r"(?:iso|din|astm|asme|en|ansi)[-\s_]*\d+[a-z0-9-]*", t):
        return True
    # 12-hex or 8-hex crawl hash directories from manifest
    if re.fullmatch(r"[0-9a-f]{8,16}", t):
        return True
    return False


